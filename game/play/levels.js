export function parseBrick(ch) {
  if (ch >= '0' && ch <= '7') return normalBrick(ch.charCodeAt(0) - 48, false);
  if (ch >= 'A' && ch <= 'H') return normalBrick(ch.charCodeAt(0) - 65, true);
  switch (ch) {
    case 's':
    case 'S': return silverBrick(1, false);
    case 'r': return silverBrick(0, true);
    case 'g': return goldBrick();
    case 'm': return MOVER;
    default: return 0;
  }
}

/** Laedt Runde round (0-basiert), Variante variant (0/1) ins Raster und setzt den Zaehler. */
export function loadLevel(round, variant, grid) {
  const rows = LEVELS[((round % ROUNDS) + ROUNDS) % ROUNDS][variant ? 1 : 0];
  grid.clear();
  for (let r = 0; r < 18 && r < rows.length; r++) {
    const row = rows[r];
    for (let c = 0; c < grid.columns && c < row.length; c++) grid.set(c, r, parseBrick(row[c]));
  }
  grid.recountRemaining();
}
